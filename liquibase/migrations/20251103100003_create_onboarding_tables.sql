/*
 * Migration: Create Onboarding Tables
 * Purpose: Create tables for tracking individual employee onboarding processes
 * Author: Database Architect
 * Date: 2025-11-03
 * 
 * This migration creates two tables:
 * 1. onboarding_process - represents one employee's onboarding journey
 * 2. onboarding_task - individual tasks copied from template_task for this process
 * 
 * Key Design Decisions:
 * - Process is automatically created when employee account is created
 * - Tasks are COPIED from template_task (not referenced), so template changes
 *   don't affect active processes (versioning via denormalization)
 * - Progress counters (total_tasks_count, completed_tasks_count) are denormalized
 *   for fast dashboard reads without expensive COUNT() queries
 * - status field supports ACTIVE and ARCHIVED states
 * - ON DELETE RESTRICT on all foreign keys forces application to handle deletions
 * 
 * Tables Created: 
 * - benew.onboarding_process
 * - benew.onboarding_task
 * 
 * Dependencies: 
 * - benew.app_user (from migration 20251103100001)
 * - benew.template (from migration 20251103100002)
 * 
 * Special Notes:
 * - Application is responsible for updating progress counters when tasks complete
 * - source_template_id is kept for audit purposes but not used for task lookup
 * - is_completed toggle triggers counter updates in application logic
 */

-- create onboarding_process table
-- represents one employee's onboarding journey from start to completion/archive
create table benew.onboarding_process (
    -- primary key: uuid generated by spring boot application
    id uuid primary key,
    
    -- foreign key to employee being onboarded
    -- one user can have multiple processes (e.g., if changing positions)
    user_id uuid not null,
    
    -- foreign key to manager overseeing this onboarding
    -- manager sees all their employees' processes on dashboard
    manager_id uuid not null,
    
    -- foreign key to template that was used to create this process
    -- kept for audit/reporting purposes only
    -- actual tasks are copied to onboarding_task table
    source_template_id uuid not null,
    
    -- process status: ACTIVE or ARCHIVED
    -- ACTIVE = currently ongoing
    -- ARCHIVED = completed and moved to archive by manager
    -- validated at application level via java enum
    status varchar(50) not null,
    
    -- denormalized progress counters for fast dashboard queries
    -- updated by application when tasks are marked complete/incomplete
    -- avoids expensive COUNT(*) queries on onboarding_task table
    total_tasks_count integer not null default 0,
    completed_tasks_count integer not null default 0,
    
    -- audit columns managed by spring data jpa auditing
    created_at timestamptz not null,
    updated_at timestamptz not null,
    
    -- foreign key to employee user
    -- on delete restrict prevents deletion of users with active onboarding
    -- application must complete/archive process before user deletion
    constraint fk_onboarding_process_user 
        foreign key (user_id) 
        references benew.app_user(id) 
        on delete restrict,
    
    -- foreign key to manager user
    -- on delete restrict prevents deletion of managers overseeing processes
    -- application must reassign processes before manager deletion
    constraint fk_onboarding_process_manager 
        foreign key (manager_id) 
        references benew.app_user(id) 
        on delete restrict,
    
    -- foreign key to source template
    -- on delete restrict prevents deletion of templates used in processes
    -- kept for audit trail even though tasks are copied
    constraint fk_onboarding_process_template 
        foreign key (source_template_id) 
        references benew.template(id) 
        on delete restrict
);

