-- create onboarding_task table
-- stores individual tasks for a specific onboarding process
-- tasks are COPIED from template_task when process is created
create table benew.onboarding_task (
    -- primary key: uuid generated by spring boot application
    id uuid primary key,
    
    -- foreign key to parent onboarding process
    -- one process can have many tasks
    onboarding_process_id uuid not null,
    
    -- task information (copied from template_task)
    -- these fields are snapshots at time of process creation
    -- changes to template tasks will NOT affect these values
    title varchar(255) not null,
    
    -- optional detailed instructions
    description text,
    
    -- display order in checklist
    task_order integer not null,
    
    -- who is responsible: MANAGER or USER
    owner_role varchar(50) not null,
    
    -- completion status
    -- toggled by task owner (manager or employee)
    -- triggers update of completed_tasks_count in onboarding_process
    is_completed boolean not null default false,
    
    -- audit columns managed by spring data jpa auditing
    created_at timestamptz not null,
    updated_at timestamptz not null,
    
    -- foreign key constraint to onboarding process
    -- on delete restrict prevents deletion of processes with tasks
    -- application must delete tasks first (or cascade would also be reasonable here)
    constraint fk_onboarding_task_process 
        foreign key (onboarding_process_id) 
        references benew.onboarding_process(id) 
        on delete restrict
);

