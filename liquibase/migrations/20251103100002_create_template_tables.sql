-- create template_task table
-- stores individual tasks that make up a template checklist
create table benew.template_task (
    -- primary key: uuid generated by spring boot application
    id uuid primary key,
    
    -- foreign key to parent template
    -- one template can have many tasks
    template_id uuid not null,
    
    -- task information
    -- title is short description displayed in checklist
    title varchar(255) not null,
    
    -- description is optional detailed instructions for the task
    -- stored as text to allow longer content
    description text,
    
    -- display order for tasks in checklist
    -- lower numbers appear first
    -- allows administrators to reorder tasks
    task_order integer not null,
    
    -- who is responsible for completing this task
    -- values: MANAGER or USER
    -- validated at application level via java enum
    owner_role varchar(50) not null,
    
    -- audit columns managed by spring data jpa auditing
    created_at timestamptz not null,
    updated_at timestamptz not null,
    
    -- foreign key constraint to template
    -- on delete restrict prevents deletion of templates that still have tasks
    -- application must delete tasks first, then template
    constraint fk_template_task_template 
        foreign key (template_id) 
        references benew.template(id) 
        on delete restrict
);

