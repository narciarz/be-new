-- create template table
-- header table for onboarding checklists, one per job position
create table benew.template (
    -- primary key: uuid generated by spring boot application
    id uuid primary key,
    
    -- unique job position name that this template applies to
    -- application normalizes this value (trim + toLowerCase) before save/search
    -- e.g., "Software Engineer", "Product Manager", etc.
    position_name varchar(50) not null,
    
    -- audit columns managed by spring data jpa auditing
    created_at timestamptz not null,
    updated_at timestamptz not null,
    
    -- unique constraint on position_name
    -- ensures only one template per job position
    -- case-insensitive uniqueness enforced via separate index in later migration
    constraint uk_template_position_name 
        unique (position_name)
);

